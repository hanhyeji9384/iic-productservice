const VISIBLE_BRANCH_CODE_SET = new Set<string>(VISIBLE_BRANCH_CODES)
const VISIBLE_GM_PRODUCT_CODE_SET = new Set<string>(VISIBLE_GM_PRODUCT_CODES)
const NON_GM_TEXT_PATTERN = /TAMBURINS|탬버린즈|NUDAKE|누데이크|NUFLA|ATII|NORSA|KENTY|MINO|CLEO|MARGIELA|GM_미국법인|US Office|FedEx|미국법인/i

export function isVisibleGmBranchCode(branchCode?: string | null) {
  if (!branchCode || branchCode === '*') return true
  return VISIBLE_BRANCH_CODE_SET.has(branchCode)
}

export function isVisibleGmText(value?: string | null) {
  return !NON_GM_TEXT_PATTERN.test(value ?? '')
}

export function isVisibleGmProductCode(productCode?: string | null) {
  if (!productCode) return true
  return VISIBLE_GM_PRODUCT_CODE_SET.has(productCode)
}

export function isVisibleGmProduct(product: {
  brandCategory?: string | null
  branchCode?: string | null
  productCode?: string | null
  name?: string | null
}) {
  return product.brandCategory === 'GENTLE MONSTER'
    && isVisibleGmBranchCode(product.branchCode)
    && isVisibleGmProductCode(product.productCode)
    && isVisibleGmText(product.name)
}

export function isVisibleGmTicket(ticket: {
  branchCode?: string | null
  productName?: string | null
  receptionPlace?: string | null
  repairDepartment?: string | null
}) {
  if (!isVisibleGmBranchCode(ticket.branchCode)) return false
  const searchableText = [
    ticket.productName,
    ticket.receptionPlace,
    ticket.repairDepartment,
  ].filter(Boolean).join(' ')
  return isVisibleGmText(searchableText)
}

